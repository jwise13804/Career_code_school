transactions = []
tid = 1
for day in range(1, 31):
    for _ in range(random.choice([2, 3, 3, 4])):
        card = random.choice(cards)
        if card[4] == "expired":
            continue
        name, cat, (lo, hi) = random.choice(merchants)
        amount = round(random.uniform(lo, hi), 2)
        if name == "Netflix":
            amount = 10.99
        if name == "Spotify":
            amount = 11.99
        status = "approved"
        r = random.random()
        if card[4] == "blocked" or r < 0.06:
            status = "declined"
        elif r < 0.22:
            status = "refunded"
        hour = random.randint(7, 22)
        minute = random.randint(0, 59)
        transactions.append((tid, card[0], name, cat, amount, "GBP", status, f"2026-09-{day:02d} {hour:02d}:{minute:02d}"))
        tid += 1

# A few disputes on approved transactions.
approved = [t for t in transactions if t[6] == "approved"]
picks = random.sample(approved, 8)
reasons = ["not received", "duplicate charge", "not recognised", "wrong amount", "faulty goods", "not received", "not recognised", "duplicate charge"]
statuses = ["opened", "under_review", "under_review", "resolved_won", "resolved_lost", "opened", "resolved_won", "under_review"]
disputes = []
for i, (t, reason, status) in enumerate(zip(sorted(picks), reasons, statuses), start=1):
    day = int(t[7][8:10])
    opened = f"2026-10-{min(28, day % 20 + 1):02d}"
    disputes.append((i, t[0], reason, status, opened))

def q(v):
    if isinstance(v, str):
        return "'" + v.replace("'", "''") + "'"
    return str(v)

